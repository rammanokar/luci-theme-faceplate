#!/usr/bin/env python3
"""Build the GitHub Pages site into _site/.

  site/index.html        landing page ({{REPO}} and {{SITE}} filled in)
  docs/screenshots/      -> _site/screenshots/
  site/demo/             -> _site/demo/  live demo: the real theme CSS and
                            JS modules from dist/, fed mock data

Usage: python3 site/build.py [--repo https://github.com/owner/name]
In GitHub Actions the repo URL comes from $GITHUB_REPOSITORY.
"""
import os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, 'luci-theme-faceplate')
OUT = os.path.join(ROOT, '_site')


def repo_urls():
    if '--repo' in sys.argv:
        repo = sys.argv[sys.argv.index('--repo') + 1].rstrip('/')
    elif os.environ.get('GITHUB_REPOSITORY'):
        repo = 'https://github.com/' + os.environ['GITHUB_REPOSITORY']
    else:
        repo = 'https://github.com/rammanokar/luci-theme-faceplate'
    owner, name = repo.split('/')[-2:]
    return repo, 'https://%s.github.io/%s/' % (owner.lower(), name)


def module(var, args, path):
    # LuCI modules are function bodies ending in a top-level `return`; wrap
    # each one in a function taking the globals LuCI would have injected.
    src = open(path).read()
    return 'var %s = (function(%s) {\n%s\n})(%s);\n' % (var, args, src, args)


def main():
    subprocess.run([ sys.executable, os.path.join(THEME, 'tools', 'build.py') ], check=True)
    dist = os.path.join(THEME, 'dist', 'www', 'luci-static')

    shutil.rmtree(OUT, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, 'site', 'demo'), os.path.join(OUT, 'demo'))
    shutil.copytree(os.path.join(dist, 'faceplate'), os.path.join(OUT, 'demo', 'luci-static', 'faceplate'))
    shutil.copytree(os.path.join(ROOT, 'docs', 'screenshots'), os.path.join(OUT, 'screenshots'))

    with open(os.path.join(OUT, 'demo', 'faceplate-modules.js'), 'w') as f:
        f.write('/* Generated by site/build.py from luci-theme-faceplate/dist. */\n')
        f.write(module('MENU', 'baseclass, ui', os.path.join(dist, 'resources', 'menu-faceplate.js')))
        f.write(module('DASH', 'view, rpc, fs, poll', os.path.join(dist, 'resources', 'view', 'faceplate', 'dashboard.js')))

    repo, site = repo_urls()
    html = open(os.path.join(ROOT, 'site', 'index.html')).read()
    open(os.path.join(OUT, 'index.html'), 'w').write(html.replace('{{REPO}}', repo).replace('{{SITE}}', site))
    open(os.path.join(OUT, '.nojekyll'), 'w').close()

    total = sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(OUT) for f in fs)
    print('site: %s (%.0f KiB), repo %s' % (os.path.relpath(OUT, ROOT), total / 1024, repo))


if __name__ == '__main__':
    main()
